const TEXT_CONTENT = { 'notes.txt': 'Shot list for the redwoods series.\n- morning fog\n- creek crossing\n- canopy from the trail\nhttps://example.test/notes\n' };
const textFor = (item) => TEXT_CONTENT[item.filename] ?? `# ${item.filename}\n\nGenerated by the fixture server.\n\n- one\n- two\n`;

// ---- fixture data -----------------------------------------------------------
const sources = [
  { name: 'filesystem', id: 0 },
  { name: 'cloud', id: 1, capabilities: { upload: false, createDirectory: false, rename: false, delete: false } } // read-only (01 CON-04, 11 MS-09)
];
const readOnly = (id) => sources.find((s) => String(s.id) === String(id))?.capabilities?.upload === false;

const DAY = 86400000;
const t0 = Date.UTC(2017, 3, 2, 14, 25); // 2017-04-02T14:25Z
const join = (dir, name) => (dir === '/' ? name : path.posix.join(dir, name));
// URLs are percent-encoded per segment (01 CON-03); the v2 server emitted raw spaces, which is not a valid URI reference.
const urlFor = p => '/sources/filesystem/' + p.split('/').map(encodeURIComponent).join('/');
function file(dir, filename, fileSize, dimensions, daysAgo) {
  const p = join(dir, filename);
  return {
    filename, directory: dir, path: p,
    absoluteURL: urlFor(p),
    absolutePreviewURL: urlFor(p),
    editedOn: t0 - daysAgo * DAY, dimensions, fileSize
  };
}
const TEXT_EXT = /\.(txt|md|json|css|js|ts|html|xml|ya?ml|sh|py)$/i;
/** Text entries preview as thumbnails while enabled (HTML-66c). */
function withPreviews(entries) { return entries.map((e) => (e.filename && TEXT_EXT.test(e.filename) ? { ...e, absolutePreviewURL: textPreviews ? `/sources/filesystem/__thumb/${encodeURI(e.path)}` : e.absoluteURL } : e)); }
function folder(dir, name) {
  const p = join(dir, name);
  return { foldername: name, directory: p, path: p, absoluteURL: urlFor(p), absolutePreviewURL: urlFor(p), editedOn: t0, fileSize: 4096 };
}
